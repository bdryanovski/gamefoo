/**
 * Built-in 16×16 pixel bitmap icon set.
 *
 * Each icon is a 16-pixel-wide, 16-pixel-tall sprite stored as an
 * array of sixteen integers. Each integer is a bitmask where bit 15
 * (MSB) corresponds to the leftmost pixel and bit 0 to the rightmost.
 *
 *   Bit layout per row  (width = 16)
 *   ┌──────────────────────────────────────────────────┐
 *   │ b15 b14 … b8  b7  b6  … b1  b0                  │
 *   │ ◄── left                       right ──►         │
 *   └──────────────────────────────────────────────────┘
 *
 * Icons are grouped into four categories:
 *   - Game UI  — heart, coin, star, gem, arrows, cross, checkmark …
 *   - Controls — dpad, buttons, key cap, mouse, cursor, gamepad …
 *   - Status   — shield, skull, mana drop, bars, lock, speech bubble …
 *   - Objects  — sword, key, potion, chest, bomb, scroll, flame …
 *
 * @category Icons
 * @since 0.4.0
 * @internal
 *
 * @example Reading an icon
 * ```ts
 * import ICONS_16x16 from "./icons_16x16";
 *
 * const heart = ICONS_16x16["heart_full"];
 * // [0, 32382, 65535, 65535, 65535, 32766, 16380, 8184, 4080, 2016, 960, 384, 0, 0, 0, 0]
 * //
 * //  ................   =     0
 * //  .######..######.   = 32382
 * //  ################   = 65535
 * //  ...
 * ```
 */

